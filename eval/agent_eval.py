def load_problems(source: str, limit: int | None = None) -> list[dict]:
    """Load problems from a source.  Supports 'humaneval' or JSON file path."""
    if source == "humaneval":
        from eval.humaneval_loader import load as load_humaneval
        # Available: 164 HumanEval problems
        return load_humaneval(limit=limit)
    elif os.path.isfile(source):
        with open(source) as f:
            problems = json.load(f)
        if isinstance(problems, dict):
            problems = [{"id": k, **v} for k, v in problems.items()]
        if limit:
            problems = problems[:limit]
        return problems
    else:
        raise ValueError(f"Unknown problem source: {source}")


def main():
    ap = argparse.ArgumentParser(
        description="Agentic evaluation for le fat chaton (terminal-bench proxy)"
    )
    ap.add_argument("--ckpt", help="Checkpoint to evaluate")
    ap.add_argument("--problems", default="humaneval",
                    help="Problem source ('humaneval' or JSON file path)")
    ap.add_argument("--limit", type=int, default=None,
                    help="Only evaluate first N problems")
    ap.add_argument("--max-steps", type=int, default=10,
                    help="Max agent loop steps per problem")
    ap.add_argument("--max-tokens", type=int, default=300,
                    help="Max new tokens per generation step")
    ap.add_argument("--temperature", type=float, default=0.7)
    ap.add_argument("--n-samples", type=int, default=1,
                    help="Test-time compute scaling: run N times, pick best")
    ap.add_argument("--out", default=None,
                    help="Write per-problem results to JSON file")
    ap.add_argument("--compare", nargs=2, metavar=("FILE_A", "FILE_B"),
                    help="Compare two saved result files (mutually exclusive)")
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()

    if args.compare:
        compare_runs(args.compare[0], args.compare[1])
        return

    if not args.ckpt:
        ap.error("--ckpt is required (or use --compare)")

    print(f"[agent_eval] loading problems from {args.problems}...")
    problems = load_problems(args.problems, args.limit)
    print(f"[agent_eval] loaded {len(problems)} problems")

    print(f"[agent_eval] evaluating checkpoint: {args.ckpt}")
    print(f"[agent_eval] settings: max_steps={args.max_steps}, "
          f"max_tokens={args.max_tokens}, temperature={args.temperature}")

    results = evaluate_batch(
        problems, args.ckpt,
        max_steps=args.max_steps,
        max_new_tokens=args.max_tokens,
        temperature=args.temperature,
        n_samples=args.n_samples,
        verbose=args.verbose,
    )

    agg = aggregate_results(results)
    print_report(agg, title=f"Agent Eval — {os.path.basename(args.ckpt)}")

    # Save results
    if args.out:
        os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
        output = {
            "ckpt": args.ckpt,
            "aggregate": agg,
            "results": [asdict(r) for r in results],
        }
        with open(args.out, "w") as f:
            json.dump(output, f, indent=2)
        print(f"[agent_eval] saved results to {args.out}")
    else:
        out_path = os.path.join(
            PROJ_ROOT, "eval", "_runs",
            f"agent_eval_{time.strftime('%Y%m%d_%H%M%S')}.json"
        )
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        output = {
            "ckpt": args.ckpt,
            "aggregate": agg,
            "results": [asdict(r) for r in results],
        }
        with open(out_path, "w") as f:
            json.dump(output, f, indent=2)
        print(f"[agent_eval] saved results to {out_path}")


if __name__ == "__main__":
    main()