# ---------------------------------------------------------------------------
# Per-problem agent evaluation
# ---------------------------------------------------------------------------

def _problem_to_task(problem: dict) -> str:
    """Convert a problem dict into an agent loop task prompt.

    Supports HumanEval format (from humaneval_loader.py) and custom JSON.
    The agent loop is seeded with the problem description and expects the
    model to write code, test it, and fix it.
    """
    prompt = problem.get("prompt", "")
    instruction = problem.get("instruction", "")
    task = problem.get("task", "")
    description = problem.get("description", "")

    # HumanEval format: prompt is a function signature + docstring
    if prompt:
        return f"Write a Python function that solves this problem:\n\n{prompt}"

    if instruction:
        return instruction

    if description:
        return description

    if task:
        return task

    # Fallback: combine all available fields
    parts = [v for v in [description, instruction, task, prompt] if v]
    return "\n\n".join(parts) if parts else str(problem)


def _try_extract_solution(conversation_log: str | None) -> str | None:
    """Extract the final code solution from the agent conversation.

    Looks for <done>, <code>, or ```python blocks.  Returns the first
    complete code block found.
    """
    if not conversation_log:
        return None
    for pattern in [
        r"<done>\s*(.*?)\s*</done>",
        r"<code>\s*(.*?)\s*</code>",
        r"```python\s*(.*?)\s*```",
        r"```\s*(.*?)\s*```",
    ]:
        m = re.search(pattern, conversation_log, re.DOTALL)
        if m:
            # If <done> contains code with backticks, extract that instead
            inner = m.group(1).strip()
            inner_m = re.search(r"```python\s*(.*?)\s*```", inner, re.DOTALL)
            if inner_m:
                return inner_m.group(1).strip()
            return inner
    return None


@dataclass
class AgentResult:
    """Result of running the agent loop on one problem."""
    problem_id: str
    solved: bool = False
    n_steps: int = 0
    n_commands: int = 0
    solution_tokens: int = 0
    wall_time_s: float = 0.0
    error: str | None = None
    solution: str | None = None
    done_message: str | None = None


def evaluate_problem(
    problem: dict,
    ckpt_path: str,
    max_steps: int = 10,
    max_new_tokens: int = 300,
    temperature: float = 0.7,
    verbose: bool = False,
) -> AgentResult:
    """Run the agent loop on one problem and return metrics."""
    problem_id = str(problem.get("problem_id", problem.get("id", "unknown")))
    task = _problem_to_task(problem)
    start = time.time()

    result = AgentResult(problem_id=problem_id)

    try:
        # Lazy import: the agent loop imports torch at module level,
        # which isn't available on the dev VM.
        from agent.loop import run as run_agent_loop

        done_message = run_agent_loop(
            task,
            ckpt_path=ckpt_path,
            max_steps=max_steps,
            max_new_tokens=max_new_tokens,
            temperature=temperature,
            verbose=verbose,
        )

        result.wall_time_s = round(time.time() - start, 2)
        result.done_message = done_message

        if done_message is not None:
            # The agent claims to have solved it
            result.solved = "pass" in done_message.lower() or "solved" in done_message.lower()
            # Also try to extract the solution for verification
            result.solution = _try_extract_solution(done_message)

    except Exception as e:
        result.wall_time_s = round(time.time() - start, 2)
        result.error = str(e)[:200]

    return result


# ---------------------------------------------------------------------------
# Batch evaluation
# ---------------------------------------------------------------------------

def evaluate_batch(
    problems: list[dict],
    ckpt_path: str,
    max_steps: int = 10,
    max_new_tokens: int = 300,
    temperature: float = 0.7,
    n_samples: int = 1,
    limit: int | None = None,
    verbose: bool = False,
) -> list[AgentResult]:
    """Evaluate the agent on all problems.  Returns list of AgentResult."""
    if limit:
        problems = problems[:limit]

    results: list[AgentResult] = []
    t0 = time.time()

    for i, problem in enumerate(problems):
        pid = problem.get("problem_id", problem.get("id", f"prob_{i}"))
        if verbose:
            print(f"[agent_eval] {i+1}/{len(problems)} {pid}...")

        best = None
        for s in range(n_samples):
            if n_samples > 1:
                # Vary temperature for diversity (test-time compute scaling)
                t = temperature + (s / max(n_samples - 1, 1)) * (0.3)  # 0.7 → 1.0
                t = min(t, 1.2)
            else:
                t = temperature
            r = evaluate_problem(
                problem, ckpt_path, max_steps, max_new_tokens, t, verbose,
            )
            if best is None or r.solved or (r.solution and not best.solution):
                best = r
            if r.solved:
                break  # Early termination: found a solution
        results.append(best or r)

        if verbose:
            status = "✓" if r.solved else "✗"
            print(f"  {status}  {r.n_steps} steps  {r.wall_time_s:.1f}s"
                  f"{'  ' + r.error if r.error else ''}")

    if verbose:
        elapsed = time.time() - t0
        n_solved = sum(1 for r in results if r.solved)
        print(f"\n[agent_eval] {n_solved}/{len(results)} solved "
              f"({elapsed:.0f}s total)")

    return results


# ---------------------------------------------------------------------------
# Aggregation and reporting
# ---------------------------------------------------------------------------

def aggregate_results(results: list[AgentResult]) -> dict:
    """Compute aggregate metrics from per-problem results."""
    n = len(results)
    if n == 0:
        return {"n_problems": 0}

    solved = [r for r in results if r.solved]
    n_solved = len(solved)

    return {
        "n_problems": n,
        "n_solved": n_solved,
        "solve_rate": round(n_solved / max(1, n), 4),
        "median_steps_solved": (
            sorted([r.n_steps for r in solved])[len(solved) // 2]
            if solved else None
        ),
        "avg_steps": round(sum(r.n_steps for r in results) / max(1, n), 2),
        "avg_commands": round(
            sum(r.n_commands for r in results) / max(1, n), 2
        ),
        "avg_time_s": round(
            sum(r.wall_time_s for r in results) / max(1, n), 2
        ),
        "n_errors": sum(1 for r in results if r.error),
    }


def print_report(agg: dict, title: str = "Agent Evaluation Report"):
    """Pretty-print the aggregate report."""
    print()
    print("=" * 56)
    print(f"  {title}")
    print("=" * 56)
    print(f"  Problems:          {agg['n_problems']}")
    print(f"  Solved:            {agg['n_solved']}")
    print(f"  Solve rate:        {agg['solve_rate']:.1%}")
    print(f"  Median steps (solved): {agg['median_steps_solved']}")
    print(f"  Avg steps:         {agg['avg_steps']}")
    print(f"  Avg commands:      {agg['avg_commands']}")
    print(f"  Avg time:          {agg['avg_time_s']:.1f}s")
    print(f"  Errors:            {agg['n_errors']}")
    print("=" * 56)


