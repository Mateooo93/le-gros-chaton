# Comparison mode
# ---------------------------------------------------------------------------

def compare_runs(path_a: str, path_b: str):
    """Load two saved result files and compare the aggregate metrics side by side."""
    with open(path_a) as f:
        data_a = json.load(f)
    with open(path_b) as f:
        data_b = json.load(f)

    agg_a = data_a.get("aggregate", data_a)
    agg_b = data_b.get("aggregate", data_b)

    keys = ["solve_rate", "avg_steps", "avg_commands", "avg_time_s"]
    print()
    print("=" * 70)
    print(f"  COMPARISON:  {os.path.basename(path_a):<25} vs  {os.path.basename(path_b):<25}")
    print("=" * 70)
    print(f"  {'Metric':<25} {'Run A':<15} {'Run B':<15} {'Δ':<10}")
    print("  " + "-" * 65)
    for key in keys:
        a = agg_a.get(key, "?")
        b = agg_b.get(key, "?")
        if isinstance(a, (int, float)) and isinstance(b, (int, float)):
            delta = b - a
            delta_str = f"{delta:+.1%}" if "rate" in key else f"{delta:+.2f}"
            print(f"  {key:<25} {a:<15} {b:<15} {delta_str:<10}")
        else:
            print(f"  {key:<25} {str(a):<15} {str(b):<15} {'?':<10}")
    print("=" * 70)

    # Winner summary
    solve_a = agg_a.get("solve_rate", 0)
    solve_b = agg_b.get("solve_rate", 0)
    if solve_b > solve_a:
        print(f"  → Run B is better (solve rate {solve_b:.1%} vs {solve_a:.1%})")
    elif solve_a > solve_b:
        print(f"  → Run A is better (solve rate {solve_a:.1%} vs {solve_b:.1%})")
    else:
        print(f"  → Same solve rate ({solve_a:.1%})")


