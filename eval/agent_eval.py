"""Agentic evaluation — the metric that matters for terminal-bench.

THE GAP
-------
``eval/eval.py`` measures one-shot pass@k: the model writes a function body
in a single forward pass.  This is a proxy metric.  The real target is whether
the model can *debug and iterate* — write code, run tests, see error output,
edit the code, rerun, and eventually pass.  That's what the agent loop does.

This file bridges the gap by scoring the FULL agent loop (not just one-shot
completions) on coding benchmarks.

METRICS
-------
Per problem:
  - solved:               Did the agent eventually pass the tests?
  - n_steps:              How many agent loop iterations did it take?
  - n_commands:           How many shell commands did the agent run?
  - solution_tokens:      Total tokens generated by the model
  - wall_time_s:          Wall-clock time for the rollout

Aggregate:
  - solve_rate:           Fraction of problems solved
  - median_steps:         Median steps-to-solve across solved problems
  - avg_commands:         Average commands per rollout
  - avg_time:             Average wall time per problem

USAGE
-----
  # Quick run (limit=10, cheap for dev loops):
  python eval/agent_eval.py --ckpt model.pt --limit 10

  # Full evaluation with comparison:
  python eval/agent_eval.py --ckpt model_rft.pt --out results/rft.json
  python eval/agent_eval.py --ckpt model_rlvr.pt --out results/rlvr.json

  # Compare two runs:
  python eval/agent_eval.py --compare results/rft.json results/rlvr.json
"""
