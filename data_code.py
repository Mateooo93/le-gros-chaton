"""Code-corpus streaming pipeline for "le fat chaton" (lazy init).

Same memmap idea as data2.py but for CODE corpora (Stack v2 / StarCoderData /
the-smol-corpus). Designed to run on a CLOUD VM (more disk than your 2070 box —
Stack v2 is huge, so we stream + sample, never pull the whole thing).

Pick the corpus with CHATON_CODE_CORPUS:
  "github-code-python" (DEFAULT) -> codeparrot/github-code filtered to Python.
                      Fully open, no gating/acceptance needed. Streams fast as
                      parquet from HF. The workhorse for a solo-budget coder.
  "python-edu"      -> HuggingFaceTB/smollm-corpus python-edu (7.6M edu-scored
                      Python files). Higher quality per token, open, but the
                      file bodies may need SWH S3 fetch (slower).
  "starcoderdata"   -> bigcode/starcoderdata python subset. GATED (accept terms
                      once at huggingface.co/datasets/bigcode/starcoderdata).
  "cosmopedia"      -> smollm-corpus synthetic textbooks (prose). Used as the
                      PROSE_BLEND for general knowledge, not a code source.
  "fineweb-edu"     -> smollm-corpus fineweb-edu-dedup (educational web). Prose.

Like data2.py: encodes once to a uint16 memmap, then streams random windows.
For a coding model the vocab stays 50257 (gpt2 BPE) — code tokenizes fine with it,
and keeping the vocab shared with the WikiText base lets you continue-pretrain
on top of an existing checkpoint if you want.
(For the BIG fat model you train from scratch, so no checkpoint reuse needed.)

Imports are side-effect free — preparation (download, tokenize, memmap, GPU
upload) happens lazily on the first call to ``get_batch``.
"""
